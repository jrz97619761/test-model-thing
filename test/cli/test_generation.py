import contextlib

import pytest


def test_generation_is_repeatable_and_does_not_change_checkpoint(
    tmp_path, checkpoint_factory
):
    from io import StringIO
    from tmt.cli import generate

    path = tmp_path / 'model.safetensors'
    checkpoint_factory(path)
    original = path.read_bytes()
    first_path, second_path = tmp_path / 'first.bin', tmp_path / 'second.bin'
    stdout = StringIO()
    with contextlib.redirect_stdout(stdout):
        first = generate(path, 'The ', first_path, 11, 16, log_every=5)
    assert [
        line
        for line in stdout.getvalue().splitlines()
        if line.startswith('generated bytes:')
    ] == [
        'generated bytes: 5/16',
        'generated bytes: 10/16',
        'generated bytes: 15/16',
    ]
    second = generate(path, 'The ', second_path, 11, 16)
    assert len(first) == 16, 'first generation returned the wrong byte count'
    assert len(second) == 16, 'second generation returned the wrong byte count'
    assert first == second
    assert first_path.read_bytes() == first
    assert second_path.read_bytes() == second
    assert path.read_bytes() == original


def test_generation_zero_bytes_writes_empty_output(tmp_path, checkpoint_factory):
    from tmt.cli import generate

    checkpoint = tmp_path / 'model.safetensors'
    output = tmp_path / 'sample.bin'
    checkpoint_factory(checkpoint)
    output.write_bytes(b'previous sample')

    generated = generate(checkpoint, 'The ', output, count=0)

    assert generated == b''
    assert output.read_bytes() == b''


@pytest.mark.parametrize(
    'initial_output',
    [b'', b'keep this sample'],
    ids=['empty-output', 'nonempty-output'],
)
def test_generation_negative_count_preserves_existing_output(
    tmp_path, checkpoint_factory, initial_output
):
    from tmt.cli import generate

    checkpoint = tmp_path / 'model.safetensors'
    output = tmp_path / 'sample.bin'
    checkpoint_factory(checkpoint)
    output.write_bytes(initial_output)

    with pytest.raises(ValueError, match='bytes must be nonnegative'):
        generate(checkpoint, 'The ', output, count=-1)

    assert output.read_bytes() == initial_output, (
        'negative count changed the existing output'
    )


@pytest.mark.parametrize('seed', [0, 2**64 - 1], ids=['minimum', 'maximum'])
def test_generation_accepts_seed_boundaries(saved_checkpoint, tmp_path, seed):
    """Check accepted endpoints. The repeatability test uses seed 11."""
    from tmt.cli import generate

    generated = generate(saved_checkpoint.path, 'X', tmp_path / 'sample.bin', seed, 1)
    assert len(generated) == 1


@pytest.mark.parametrize('temperature', [0, 0.05], ids=['zero', 'below-floor'])
def test_temperature_floor(saved_checkpoint, tmp_path, temperature):
    from tmt.cli import generate

    path, output = saved_checkpoint.path, tmp_path / 'sample.bin'
    minimum = generate(path, 'The ', output, count=2, temperature=0.1)
    assert generate(path, 'The ', output, count=2, temperature=temperature) == minimum


@pytest.mark.parametrize(
    'temperature',
    [float('nan'), float('inf'), -float('inf'), -0.1],
    ids=['nan', 'positive-infinity', 'negative-infinity', 'negative'],
)
@pytest.mark.parametrize(
    'existing', [False, True], ids=['new-output', 'existing-output']
)
def test_invalid_temperature(tmp_path, monkeypatch, forbid_call, existing, temperature):
    from tmt.cli import generate

    monkeypatch.setattr('tmt.cli.load_model', forbid_call)
    output = tmp_path / 'sample.bin'
    if existing:
        output.write_bytes(b'keep')
    with pytest.raises(
        ValueError, match='temperature must be a finite nonnegative number'
    ):
        generate('missing.safetensors', 'The ', output, temperature=temperature)
    if existing:
        assert output.read_bytes() == b'keep'
    else:
        assert not output.exists()
